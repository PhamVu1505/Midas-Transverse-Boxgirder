def write_elem_depmatl(geo: CrossSectionGeometry) -> str:
    """Write *ELEM-DEPMATL section (V/S ratios)."""
    lines = [
        '',
        '*ELEM-DEPMATL    ; Change Element Dependent Material Property',
        '; ELEM_LIST, TYPE, H(VS)',
    ]

    h = geo.H
    scale = h / 3.2  # Scale factor relative to S16

    # V/S ratio data (pattern from S16 reference, scaled by H)
    vs_data = [
        ('108 119', round(geo.t_top_center / (2 * 0.85), 6)),
        ('16 19', round(0.333 * scale, 6)),
        ('110 117', round(geo.t_top_center / (1.0 + 0.16), 6)),
        ('126', round(0.21 * scale, 6)),
        ('125', round(0.228 * scale, 6)),
        ('109 118', round(geo.t_top_center / 0.97, 6)),
        ('14 21', round(0.353 * scale, 6)),
        ('3 10', round(geo.t_bot_center / 0.74, 6)),
        ('1 12', round(0.478 * scale, 6)),
        ('201 202', round(0.355 * scale, 6)),
        ('111to116', round(geo.t_top_center / 1.3, 6)),
        ('104 123', round(0.319 * scale, 6)),
        ('4to9', round(geo.t_bot_center / 0.786, 6)),
        ('13 22', round(0.373 * scale, 6)),
        ('2 11', round(0.456 * scale, 6)),
        ('17 18', round(0.334 * scale, 6)),
        ('105 122', round(0.357 * scale, 6)),
        ('103', round(0.269 * scale, 6)),
        ('124', round(0.268 * scale, 6)),
        ('15 20', round(0.333 * scale, 6)),
        ('106 107 120 121', round(geo.t_top_at_web / (2 * 0.867), 6)),
        ('101', round(0.211 * scale, 6)),
        ('102', round(0.230 * scale, 6)),
    ]

    for elem_list, vs in vs_data:
        lines.append(f'   {elem_list}, NSM, {vs}')

    return '\n'.join(lines)


