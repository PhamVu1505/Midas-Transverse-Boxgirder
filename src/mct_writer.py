def write_header(geo: CrossSectionGeometry) -> str:
    now = datetime.now()
    lines = [
        ';---------------------------------------------------------------------------',
        ';  MIDAS/Civil Text(MCT) File.',
        f';  Date : {now.year}/{now.month}/{now.day}',
        f';  Section: {geo.name}',
        ';  Generated by mct_generator (modular)',
        ';---------------------------------------------------------------------------',
        '',
        '*VERSION',
        '   9.1.0',
    ]
    return '\n'.join(lines)


